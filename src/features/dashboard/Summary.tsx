import { Square, Volume2 } from 'lucide-react'
import { Button, GroupBox } from '../../components/retro'

interface SummaryProps {
  text: string
  speech: { supported: boolean; speaking: boolean; speak: (text: string) => void; stop: () => void }
}

// Plain-language summary of the day, with a button to have it read aloud.
export function Summary({ text, speech }: SummaryProps) {
  return (
    <GroupBox title="Summary">
      <div className="flex flex-col gap-2 sm:flex-row sm:items-start">
        <p className="r-sunken m-0 min-w-0 flex-1 px-2.5 py-2 text-[1.1em] leading-snug">{text}</p>
        {speech.supported && (
          <Button
            aria-pressed={speech.speaking}
            onClick={() => (speech.speaking ? speech.stop() : speech.speak(text))}
            icon={speech.speaking ? <Square size={14} /> : <Volume2 size={14} />}
          >
            {speech.speaking ? 'Stop reading' : 'Read aloud'}
          </Button>
        )}
      </div>
      <p className="m-0 mt-2 text-[0.92em] text-[var(--text-muted)]">
        Written from Open-Meteo forecast data by fixed rules, not generated by AI. Forecasts can be wrong.
      </p>
    </GroupBox>
  )
}
