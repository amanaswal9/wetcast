r"""Turn the original ronin drawing (docs/share/ronin.svg) into the ASCII art on Wetcast's desktop.

Run from the repository root with the project's Python environment (Playwright + Chromium):
    & "$HOME\.venvs\weatherai\Scripts\python.exe" docs/share/make_ronin_ascii.py

Chromium draws the SVG, each character cell is measured, and a value from 0 to 1 picks a
character from a ramp (no asterisks). Two versions go into src/lib/roninArt.ts:

- RONIN_INK: dark characters on a light background, density following how dark the drawing is.
- RONIN_LIGHT: light characters on a dark background. Inside the figure the density follows how
  light it is (face and hands bright), with a faint floor so the dark hair and robe keep their shape.

It also saves docs/share/ronin-preview.png, the drawing as Chromium sees it.
"""

import re
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "docs" / "share" / "ronin.svg"
OUT = ROOT / "src" / "lib" / "roninArt.ts"
PREVIEW = ROOT / "docs" / "share" / "ronin-preview.png"

COLUMNS = 104
# Characters are about twice as tall as they are wide, so a cell covers two pixels down per pixel across.
CHAR_ASPECT = 2.0
# From empty to fully drawn.
RAMP = " .,:;-~=+o#%@"

# Measures every cell in the page: [darkness over the whole cell, share of the cell inside the
# figure, lightness of the part inside the figure], each from 0 to 1.
MEASURE_JS = """async ([cols, rows, cw, ch, w, h]) => {
  const draw = async (svg, withPage) => {
    const img = new Image()
    img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg.outerHTML)
    await img.decode()
    const c = document.createElement('canvas'); c.width = w; c.height = h
    const g = c.getContext('2d')
    if (withPage) { g.fillStyle = '#fff'; g.fillRect(0, 0, w, h) }
    g.drawImage(img, 0, 0, w, h)
    return g.getImageData(0, 0, w, h).data
  }
  const svg = document.querySelector('svg')
  const px = await draw(svg, true)
  // Without the white page, only the figure's own pixels are opaque.
  const bare = svg.cloneNode(true)
  bare.querySelector('rect').remove()
  const alpha = await draw(bare, false)
  const out = []
  for (let r = 0; r < rows; r++) {
    const line = []
    for (let k = 0; k < cols; k++) {
      let dark = 0, n = 0, cover = 0, light = 0
      for (let y = Math.floor(r * ch); y < Math.floor((r + 1) * ch); y++)
        for (let x = Math.floor(k * cw); x < Math.floor((k + 1) * cw); x++) {
          const i = (y * w + x) * 4
          const d = 1 - (px[i] + px[i + 1] + px[i + 2]) / 765
          dark += d; n++
          if (alpha[i + 3] > 128) { cover++; light += 1 - d }
        }
      line.push([n ? dark / n : 0, n ? cover / n : 0, cover ? light / cover : 0])
    }
    out.push(line)
  }
  return out
}"""


def measure() -> list[list[list[float]]]:
    """Draw the SVG in Chromium and measure every character cell."""
    svg = SVG.read_text(encoding="utf-8")
    width, height = (int(v) for v in re.search(r'width="(\d+)" height="(\d+)"', svg).groups())
    cell_w = width / COLUMNS
    cell_h = cell_w * CHAR_ASPECT
    rows = int(height / cell_h)
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        page = browser.new_page(viewport={"width": width, "height": height})
        page.set_content(f"<body style='margin:0'>{svg}</body>")
        page.screenshot(path=str(PREVIEW))
        cells = page.evaluate(MEASURE_JS, [COLUMNS, rows, cell_w, cell_h, width, height])
        browser.close()
    return cells


def to_rows(cells, value_of) -> list[str]:
    """One string per row, a ramp character per cell, with trailing spaces removed."""
    top = len(RAMP) - 1
    return ["".join(RAMP[min(top, round(value_of(c) * top))] for c in row).rstrip() for row in cells]


def ink_value(cell) -> float:
    return cell[0]


def light_value(cell) -> float:
    _, cover, light = cell
    if cover < 0.25:
        return 0.0
    return max(0.09, cover * light)


def main() -> None:
    cells = measure()
    ink = to_rows(cells, ink_value)
    light = to_rows(cells, light_value)
    # Trim rows that are empty in both versions, so the two stay the same height and line up.
    while ink and not ink[0] and not light[0]:
        ink.pop(0)
        light.pop(0)
    while ink and not ink[-1] and not light[-1]:
        ink.pop()
        light.pop()

    nl = "\n"
    for art in (nl.join(ink), nl.join(light)):
        # Characters that would break the TypeScript template literal, and the asterisks the owner ruled out.
        assert not set(art) & {"*", "`", "$", "\\"}

    OUT.write_text(
        "// Generated by docs/share/make_ronin_ascii.py from docs/share/ronin.svg (an original drawing).\n"
        "// Edit the drawing and run the script again rather than changing this by hand.\n\n"
        "// Dark characters on a light background.\n"
        f"export const RONIN_INK = `\n{nl.join(ink)}\n`\n\n"
        "// Light characters on a dark background.\n"
        f"export const RONIN_LIGHT = `\n{nl.join(light)}\n`\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(ink)} rows, {COLUMNS} columns")


if __name__ == "__main__":
    main()
